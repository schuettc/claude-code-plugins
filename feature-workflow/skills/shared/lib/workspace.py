"""Scaffold a multi-repo workspace.

A workspace is a thin coordination repo with member repos nested inside it as
gitignored, independent clones. It is identified by its `.feature-workspace.yml`
manifest, not its name. Written by `feature-init --workspace`.
"""

import json
import re
from pathlib import Path

# Matches a member entry `- { dir: engine, repo: owner/engine }` in the manifest.
# The commented contract/deploy examples lack the `, repo:` tail, so they're skipped.
_MEMBER_RE = re.compile(r"dir:\s*([\w.-]+)\s*,\s*repo:\s*([\w./-]+)")

# `- { id: engine:engine-api, owner: engine, consumers: [app, cli], kind: http }`
_CONTRACT_RE = re.compile(
    r"id:\s*([\w:./-]+)\s*,\s*owner:\s*([\w.-]+)\s*,\s*consumers:\s*\[([^\]]*)\]"
    r"\s*(?:,\s*kind:\s*([\w.-]+))?"
)

# `- { group: engine-stack, dir: engine }`
_DEPLOY_RE = re.compile(r"group:\s*([\w.-]+)\s*,\s*dir:\s*([\w.-]+)")

MANIFEST_TEMPLATE = """\
# .feature-workspace.yml — multi-repo workspace manifest.
# Identifies this directory as a workspace and lists member repos + the
# contracts between them. The topology graph the tooling reads (clone members,
# warn on contract edits, order epic children + deploys).
org: {org}
members:
{members_block}
# contracts:
#   - {{ id: engine:engine-api, owner: engine, consumers: [app], kind: http }}
# deploy:
#   - {{ group: engine-stack, dir: engine }}
"""

GITIGNORE_HEADER = "# Member repos are independent git repositories — tracked separately, not here."

SETTINGS_JSON = {
    "permissions": {
        # Member repos are addressed from the workspace root with git -C / gh -R.
        "allow": ["Bash(git -C *)", "Bash(gh -R *)"]
    }
}

WORKSPACE_CONFIG = """\
# Feature workflow configuration for the WORKSPACE repo's own features + epics.
# Written by /feature-init --workspace — edit anytime.
branch:
  prefix: "feature/"    # Branch naming: <prefix><feature-id>
  target: "main"        # Base branch for PRs and merges
reviewer: "none"        # External reviewer: gemini, codex, or none
"""

INITIAL_DASHBOARD = """\
# Feature Dashboard

*Auto-generated by hooks. Do not edit directly.*

## In Progress

*No features in progress*

## Backlog

*No features in backlog. Use `/feature-capture` to add one.*

## Completed

*No completed features*
"""

CLAUDE_MD_TEMPLATE = """\
# {org} workspace

Coordination root for the {org} multi-repo project. Launch Claude **here** — every
member repo is in the working tree, so cross-repo edits never prompt.

## Repos

| Local dir | Remote | Role |
|-----------|--------|------|
{repo_rows}

## Conventions

- Each member is an **independent git repo**. Operate on one from here with
  `git -C <dir> ...` and `gh -R <owner/repo> ...` (both allowlisted in
  `.claude/settings.json`).
- A **single-repo** feature lives in that member's `docs/features/`. **Cross-repo**
  work is an **epic** here in the workspace `docs/features/`, one child per member.
- **Cross-repo docs** (serving 2+ repos) live in this workspace's `docs/`.
"""

CLONE_MEMBERS_SH = r"""#!/bin/bash
# Clone every member repo listed in .feature-workspace.yml into this workspace.
# Idempotent: skips members already present. Run after cloning the workspace repo.
set -u
cd "$(dirname "$0")/.." || exit 1

python3 -c '
import re, pathlib
text = pathlib.Path(".feature-workspace.yml").read_text()
for m in re.finditer(r"dir:\s*([\w.-]+)\s*,\s*repo:\s*([\w./-]+)", text):
    print(m.group(1), m.group(2))
' | while read -r dir repo; do
  [ -z "$dir" ] && continue
  if [ -d "$dir/.git" ]; then
    echo "OK  $dir (already present)"
    continue
  fi
  echo "==> cloning $repo -> $dir"
  gh repo clone "$repo" "$dir" 2>/dev/null || git clone "git@github.com:$repo.git" "$dir"
done
"""


def is_workspace(root: Path) -> bool:
    """True if `root` is a multi-repo workspace (carries a manifest)."""
    return (Path(root) / ".feature-workspace.yml").exists()


def load_members(workspace_root: Path) -> list[dict]:
    """Return the member ``{dir, repo}`` entries from the workspace manifest.

    Returns an empty list when there is no manifest, so callers can treat a
    plain repo and a workspace uniformly.
    """
    manifest = Path(workspace_root) / ".feature-workspace.yml"
    if not manifest.exists():
        return []
    return [
        {"dir": m.group(1), "repo": m.group(2)}
        for m in _MEMBER_RE.finditer(manifest.read_text())
    ]


def resolve_target_repo(workspace_root: Path, target: str | None = None) -> dict:
    """Resolve which repo a feature operation should act on.

    Returns ``{dir, root, repo, is_workspace}`` where ``root`` is the path to
    cd into / run ``git -C`` against and ``repo`` is the ``owner/name`` slug for
    ``gh -R`` (``None`` for the workspace's own repo, which is the current dir).
    Raises ValueError if ``target`` is not the workspace or a known member.
    """
    workspace_root = Path(workspace_root)
    members = {m["dir"]: m["repo"] for m in load_members(workspace_root)}
    if target in (None, "", ".", str(workspace_root)):
        return {"dir": ".", "root": workspace_root, "repo": None, "is_workspace": True}
    if target in members:
        return {
            "dir": target,
            "root": workspace_root / target,
            "repo": members[target],
            "is_workspace": False,
        }
    raise ValueError(
        f"'{target}' is not a member of this workspace. Members: {sorted(members)}"
    )


def parse_feature_ref(ref: str) -> tuple[str | None, str]:
    """Split a feature reference into ``(repo, feature_id)``.

    ``engine:engine-api`` -> ``("engine", "engine-api")`` (a cross-repo epic
    child); a bare ``engine-api`` -> ``(None, "engine-api")`` (same repo).
    """
    if ":" in ref:
        repo, fid = ref.split(":", 1)
        return repo.strip(), fid.strip()
    return None, ref.strip()


def format_feature_ref(repo: str | None, feature_id: str) -> str:
    """Inverse of parse_feature_ref. ``repo`` None -> bare id."""
    return f"{repo}:{feature_id}" if repo else feature_id


def load_contracts(workspace_root: Path) -> list[dict]:
    """Read the standing contracts from the manifest (commented lines ignored).

    Each entry: ``{id, owner, consumers: [dir, ...], kind}``.
    """
    manifest = Path(workspace_root) / ".feature-workspace.yml"
    if not manifest.exists():
        return []
    out: list[dict] = []
    for line in manifest.read_text().splitlines():
        if line.lstrip().startswith("#"):
            continue
        m = _CONTRACT_RE.search(line)
        if m:
            consumers = [c.strip() for c in m.group(3).split(",") if c.strip()]
            out.append(
                {"id": m.group(1), "owner": m.group(2), "consumers": consumers, "kind": m.group(4) or ""}
            )
    return out


def load_deploy_groups(workspace_root: Path) -> list[dict]:
    """Read ordered deploy groups from the manifest (commented lines ignored).

    Order is preserved as authored — producer-first — so a coordinated deploy
    walks them top to bottom. Each entry: ``{group, dir}``.
    """
    manifest = Path(workspace_root) / ".feature-workspace.yml"
    if not manifest.exists():
        return []
    out: list[dict] = []
    for line in manifest.read_text().splitlines():
        if line.lstrip().startswith("#"):
            continue
        m = _DEPLOY_RE.search(line)
        if m:
            out.append({"group": m.group(1), "dir": m.group(2)})
    return out


def select_deploy_groups(workspace_root: Path, member_dirs: list[str] | None = None) -> list[dict]:
    """Deploy groups in manifest (producer-first) order, optionally narrowed to
    a set of member dirs (e.g. the members an epic touched). ``None`` -> all."""
    groups = load_deploy_groups(workspace_root)
    if member_dirs is None:
        return groups
    keep = set(member_dirs)
    return [g for g in groups if g["dir"] in keep]


def contract_consumers(workspace_root: Path, member_dir: str) -> list[dict]:
    """Contracts owned by ``member_dir`` that have at least one consumer.

    Drives the contract-edit warning: editing a producer with downstream
    consumers should prompt coordinating the change as an epic.
    """
    return [
        c for c in load_contracts(workspace_root)
        if c["owner"] == member_dir and c["consumers"]
    ]


def build_contract_warning(workspace_root: Path, member_dir: str) -> str | None:
    """Warning text shown when editing a producer member, or None if there's
    nothing downstream to break."""
    contracts = contract_consumers(workspace_root, member_dir)
    if not contracts:
        return None
    listed = "; ".join(f"{c['id']} → consumers: {', '.join(c['consumers'])}" for c in contracts)
    return (
        f"⚠️ Editing `{member_dir}`, a producer of cross-repo contract(s) [{listed}]. "
        "Reshaping a contract can break its consumers. If this change alters the "
        "contract's shape, coordinate it as a cross-repo epic (/feature-capture, "
        "type: Epic — one child per affected repo) and roll out producer-first with "
        "an expand/contract migration so consumers are never broken mid-flight."
    )


def _members_block(members: list[dict]) -> str:
    return "\n".join(f"  - {{ dir: {m['dir']}, repo: {m['repo']} }}" for m in members)


def _append_if_missing(path: Path, block: str, marker: str) -> None:
    existing = path.read_text() if path.exists() else ""
    if marker in existing:
        return
    sep = "" if (not existing or existing.endswith("\n")) else "\n"
    with open(path, "a") as f:
        f.write(sep + block)


def scaffold_workspace(root: Path, org: str, members: list[dict]) -> None:
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)

    # Manifest (workspace identity). Always (re)written — it's the source of truth.
    (root / ".feature-workspace.yml").write_text(
        MANIFEST_TEMPLATE.format(org=org, members_block=_members_block(members))
    )

    # .gitignore: members + build artifacts + the local Claude override + the
    # derived dashboard. NOTE: only `.claude/settings.local.json` is ignored —
    # the shared `.claude/settings.json` (the allowlist) stays tracked so
    # teammates get it.
    member_lines = "".join(f"{m['dir']}/\n" for m in members)
    block = (
        f"\n{GITIGNORE_HEADER}\n{member_lines}"
        "\n# Build artifacts\nnode_modules/\n"
        "\n# Local Claude state (the shared .claude/settings.json stays tracked)\n"
        ".claude/settings.local.json\n"
        "\n# Auto-generated locally by hooks — not committed\ndocs/features/DASHBOARD.md\n"
    )
    _append_if_missing(root / ".gitignore", block, "docs/features/DASHBOARD.md")

    # CLAUDE.md topology skeleton.
    claude_md = root / "CLAUDE.md"
    if not claude_md.exists():
        rows = "\n".join(f"| `{m['dir']}` | {m['repo']} | |" for m in members)
        claude_md.write_text(CLAUDE_MD_TEMPLATE.format(org=org, repo_rows=rows))

    # .claude/settings.json — allowlist member git/gh so cross-repo ops don't prompt.
    claude_dir = root / ".claude"
    claude_dir.mkdir(exist_ok=True)
    settings_path = claude_dir / "settings.json"
    if not settings_path.exists():
        settings_path.write_text(json.dumps(SETTINGS_JSON, indent=2) + "\n")

    # The workspace repo's own feature config (it runs workspace features + epics).
    cfg_path = root / ".feature-workflow.yml"
    if not cfg_path.exists():
        cfg_path.write_text(WORKSPACE_CONFIG)

    # docs/features/ with an initial dashboard.
    features_dir = root / "docs" / "features"
    features_dir.mkdir(parents=True, exist_ok=True)
    dashboard = features_dir / "DASHBOARD.md"
    if not dashboard.exists():
        dashboard.write_text(INITIAL_DASHBOARD)

    # One-command bootstrap to clone members per the manifest.
    scripts_dir = root / "scripts"
    scripts_dir.mkdir(exist_ok=True)
    clone_script = scripts_dir / "clone-members.sh"
    if not clone_script.exists():
        clone_script.write_text(CLONE_MEMBERS_SH)
        clone_script.chmod(0o755)
